void cipher(uint32_t stateshare[16][2]){
    // Round 0
    addroundkey_share(stateshare, 0, 2);

    // Rounds 1 to 9
    for (int round = 1; round < 2; round++) {
        for (int i = 0; i < 16; i++) {
            subbyte_rp_share_func(stateshare[i], 2);
        }
        shiftrows_share(stateshare, 2);
        mixcolumns_share(stateshare, 2);
        addroundkey_share(stateshare, round, 2);
    }

    // Round 10
    for (int i = 0; i < 16; i++) {
        subbyte_rp_share_func(stateshare[i], 2);
    }
    shiftrows_share(stateshare, 2);
    addroundkey_share(stateshare, 10, 2);
}



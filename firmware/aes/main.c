uint32_t multx(byte x)
{
  uint32_t y=x;
  y=y << 1;
  // if((x & 0x80)!=0)  y=y ^ 0x1b;
  byte m[]={0,0x1b};
  y^=m[x >> 7];
  return y;
}


// Computes z=x*y in GF(2^8) using four 8-bit tables 
byte multtable(byte x, byte y)
{
  register uint32_t idx0 = (uint32_t)((x & 0x0F) << 4) ^ (uint32_t)(y & 0x0F);
  register uint32_t idx1 = (uint32_t)( x & 0xF0)       ^ (uint32_t)(y & 0x0F) ^ 0x100;
  register uint32_t idx2 = (uint32_t)((x & 0x0F) << 4) ^ (uint32_t)(y >> 4)   ^ 0x200;
  register uint32_t idx3 = (uint32_t)( x & 0xF0)       ^ (uint32_t)(y >> 4)   ^ 0x300;

  register uintptr_t base = (uintptr_t)tsmult;

  // Since tsmult is 1024 aligned, we can just append the offset and do not have to use add.
  register byte p0 = *(byte *)(base ^ idx0);
  register byte p1 = *(byte *)(base ^ idx1);
  register byte p2 = *(byte *)(base ^ idx2);
  register byte p3 = *(byte *)(base ^ idx3);
  
  register byte res = 0;
  res ^= p0;
  res ^= p1;
  res ^= p2;
  res ^= p3;
  return res;
}

// The shared multiplication SecMult of Rivain-Prouff

void subbyte_rp_share_func(uint32_t a[2], int n)
{
  int i;
  uint32_t z[2], z2[2];
  uint32_t one[2];

  for(i=1;i<n;i++)
    one[i]=0;

  one[0]=1;

  for(i = 0; i < n; ++i){
    z[i] = a[i];
  }
  square_share(z, n);    

  multshare(z, one, z2, n);
  for(i = 0; i < n; ++i){
    z[i] = z2[i];
  }

  uint32_t y[2];
  multshare(z, a, y, n);

  uint32_t w[2];
  for(i = 0; i < n; ++i){
    w[i] = y[i];
  }
  square_share(w, n);
  square_share(w, n);

  uint32_t w2[2];
  multshare(w, one, w2, n);
  for(i = 0; i < n; ++i){
    w[i] = w2[i];
  }

  uint32_t y2[2];
  multshare(y, w, y2, n);

  square_share(y2, n);
  square_share(y2, n);
  square_share(y2, n);
  square_share(y2, n);
  
  multshare(w, y2, y, n);
  multshare(y, z, a, n);

  for(i=0;i<n;i++)
    a[i]=taffine[(byte)a[i]];
  if((n%2)==0)
    a[0]^=0x63;
}


